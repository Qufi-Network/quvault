/*
 * Copies the compiled Palm Wallet's creation code out of the Hardhat workspace into
 * src/palm-wallet-code.js, which the server and the browser use to work out a wallet's address
 * before it exists and to build it on its first payment.
 *
 *   cd contracts && npx hardhat compile && cd .. && node scripts/export-palm-wallet.js
 *
 * The file records a hash of the contract source it was built from, and a test fails when the
 * source changes without this being run again, so the code that ships is always the code tested.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'contracts', 'contracts', 'PalmWallet.sol');
const artifact = path.join(root, 'contracts', 'artifacts', 'contracts', 'PalmWallet.sol', 'PalmWallet.json');

const { bytecode, contractName } = JSON.parse(fs.readFileSync(artifact, 'utf8'));
if (contractName !== 'PalmWallet' || !/^0x[0-9a-f]+$/.test(bytecode)) throw new Error('That is not the Palm Wallet artifact.');
// Line endings normalised, so a Windows checkout and a Unix one agree on the hash.
const sourceHash = crypto.createHash('sha256').update(fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n')).digest('hex');

const out = `// Generated by scripts/export-palm-wallet.js from contracts/contracts/PalmWallet.sol. Do not edit.
// solc 0.8.28, optimizer on, 200 runs, evm cancun: see contracts/hardhat.config.js.
export const PALM_WALLET_SOURCE_SHA256 = '${sourceHash}';
export const PALM_WALLET_CREATION_CODE = '${bytecode}';
`;
fs.writeFileSync(path.join(root, 'src', 'palm-wallet-code.js'), out);
console.log(`src/palm-wallet-code.js: ${(bytecode.length - 2) / 2} bytes of creation code, source ${sourceHash.slice(0, 12)}`);
